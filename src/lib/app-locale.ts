const MESSAGES: Record<AppLocale, Messages> = { ru: RU, uz: UZ, en: EN }

export function translate(locale: AppLocale, key: AppMessageKey, values?: Record<string, string | number>): string {
  let message = MESSAGES[locale][key] ?? RU[key]
  for (const [name, value] of Object.entries(values ?? {})) {
    message = message.replaceAll(`{${name}}`, String(value))
  }
  return message
}

export function localeTag(locale: AppLocale): string {
  if (locale === "uz") return "uz-UZ"
  if (locale === "en") return "en-US"
  return "ru-RU"
}

export function formatClubMoney(amount: number, currency: string, locale: AppLocale): string {
  const number = new Intl.NumberFormat(localeTag(locale), {
    maximumFractionDigits: Number.isInteger(amount) ? 0 : 2,
  }).format(amount)
  if (currency === "UZS") return `${number} ${locale === "uz" ? "so‘m" : locale === "en" ? "UZS" : "сум"}`
  if (currency === "USD") return `$${number}`
  if (currency === "RUB") return `${number} ₽`
  return `${number} ${currency}`
}
